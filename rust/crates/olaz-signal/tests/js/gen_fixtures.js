// Generates tests/fixtures/js_scenario.json from the real bundled JS library.
//   node tests/js/gen_fixtures.js
// Two fresh TEST parties, X3DH with a one-time prekey, messages both ways, out-of-order
// delivery, several ratchet turns. Every step snapshots both parties' persisted store
// (the exact `zaloE2EEPCStoreV1` JSON the app writes to SQLite).
'use strict';
const fs = require('fs');
const path = require('path');
const { load } = require('./harness');

(async () => {
  const E = load().pc;
  const ALICE = 'alice-test';
  const BOB = 'bob-test';
  // Remote device ids as each side addresses the other (Zalo uses small ints; mix them).
  const BOB_DEV_FOR_ALICE = 1;
  const ALICE_DEV_FOR_BOB = 2;

  const a0 = await E.initOrRestore(ALICE, '');
  const b0 = await E.initOrRestore(BOB, '');

  const steps = [];
  const snapshots = [];
  const snap = (label) => {
    snapshots.push({
      after_step: steps.length,
      label,
      alice: E.exportStore(ALICE),
      bob: E.exportStore(BOB),
    });
  };
  snap('initial');

  const enc = async (from, to, dev, text) => {
    const uid = from, peer = to;
    const r = await E.encryptCipher(uid, peer, dev, text, 'string');
    if (!r.ok) throw new Error('encrypt failed: ' + r.error);
    steps.push({ op: 'encrypt', from: uid, to: peer, device: dev, plaintext: text, cipher: r.cipher, type: r.type });
    snap(`${from}->${to} "${text}"`);
    return r.cipher;
  };
  const dec = async (at, from, dev, cipher, text) => {
    const r = await E.decryptCipher(at, from, dev, cipher, 'string');
    if (!r.ok) throw new Error('decrypt failed: ' + r.error);
    if (r.text !== text) throw new Error('plaintext mismatch ' + r.text + ' vs ' + text);
    steps.push({ op: 'decrypt', at, from, device: dev, plaintext: text, cipher });
    snap(`${at} <- ${from} "${text}"`);
  };

  // Alice builds a session from Bob's published bundle (what Zalo's server hands out).
  const pb = await E.processPreKeyBundle(ALICE, BOB, BOB_DEV_FOR_ALICE, b0.bundlePayload);
  if (!pb.ok) throw new Error(pb.error);
  steps.push({ op: 'process_bundle', at: ALICE, remote: BOB, device: BOB_DEV_FOR_ALICE });
  snap('alice processed bob bundle');

  // Round 1: Alice -> Bob, three PreKeyWhisperMessages, delivered out of order (2, 1, 3).
  const a1 = await enc(ALICE, BOB, BOB_DEV_FOR_ALICE, 'alice 1: xin chào');
  const a2 = await enc(ALICE, BOB, BOB_DEV_FOR_ALICE, 'alice 2: how are you? 😀');
  const a3 = await enc(ALICE, BOB, BOB_DEV_FOR_ALICE, 'alice 3');
  await dec(BOB, ALICE, ALICE_DEV_FOR_BOB, a2, 'alice 2: how are you? 😀');
  await dec(BOB, ALICE, ALICE_DEV_FOR_BOB, a1, 'alice 1: xin chào');
  await dec(BOB, ALICE, ALICE_DEV_FOR_BOB, a3, 'alice 3');

  // Round 2: Bob -> Alice (DH ratchet step), delivered out of order (2, 1).
  const b1 = await enc(BOB, ALICE, ALICE_DEV_FOR_BOB, 'bob 1');
  const b2 = await enc(BOB, ALICE, ALICE_DEV_FOR_BOB, 'bob 2');
  await dec(ALICE, BOB, BOB_DEV_FOR_ALICE, b2, 'bob 2');
  await dec(ALICE, BOB, BOB_DEV_FOR_ALICE, b1, 'bob 1');

  // Round 3: Alice -> Bob (now plain WhisperMessages), five messages, delivered 4,2,5,1,3.
  const c = [];
  for (let i = 1; i <= 5; i++) c.push(await enc(ALICE, BOB, BOB_DEV_FOR_ALICE, `alice r3 #${i}`));
  for (const i of [4, 2, 5, 1, 3]) await dec(BOB, ALICE, ALICE_DEV_FOR_BOB, c[i - 1], `alice r3 #${i}`);

  // Round 4: Bob -> Alice, then Alice -> Bob again (another full ratchet turn), in order.
  const d1 = await enc(BOB, ALICE, ALICE_DEV_FOR_BOB, 'bob r4 #1');
  await dec(ALICE, BOB, BOB_DEV_FOR_ALICE, d1, 'bob r4 #1');
  const e1 = await enc(ALICE, BOB, BOB_DEV_FOR_ALICE, 'alice r4 #1');
  await dec(BOB, ALICE, ALICE_DEV_FOR_BOB, e1, 'alice r4 #1');

  // Round 5: leave one message in flight (encrypted by Bob, not yet delivered to Alice) and one
  // skipped message in Alice's store, so the final snapshots carry cached message keys.
  const f1 = await enc(BOB, ALICE, ALICE_DEV_FOR_BOB, 'bob r5 #1 (late)');
  const f2 = await enc(BOB, ALICE, ALICE_DEV_FOR_BOB, 'bob r5 #2');
  await dec(ALICE, BOB, BOB_DEV_FOR_ALICE, f2, 'bob r5 #2');
  void f1; // f1 stays undelivered in the last snapshot; tests deliver it from Rust.

  const out = {
    note: 'TEST KEYS ONLY. Generated by tests/js/gen_fixtures.js from the real bundled libsignal-protocol.js.',
    alice: { uid: ALICE, remote_device_for_bob: BOB_DEV_FOR_ALICE },
    bob: { uid: BOB, remote_device_for_alice: ALICE_DEV_FOR_BOB },
    bob_bundle: b0.bundlePayload,
    steps,
    snapshots,
  };
  const dest = path.resolve(__dirname, '../fixtures/js_scenario.json');
  fs.writeFileSync(dest, JSON.stringify(out, null, 1));
  console.log('wrote', dest, 'steps', steps.length, 'snapshots', snapshots.length);
})().catch((e) => { console.error(e); process.exit(1); });
